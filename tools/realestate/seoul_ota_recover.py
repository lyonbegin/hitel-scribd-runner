#!/usr/bin/env python3
"""Restore highest valid GitHub Actions checkpoint artifact if ahead of repository state.

Never resets current progress to an older run. Preserve current manually reviewed
source evidence. Requires actions:read and GH_TOKEN in GitHub Actions.
"""
from __future__ import annotations
import datetime as dt
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT=Path("data/seoul-ota")
REPO=os.environ.get("GITHUB_REPOSITORY","lyonbegin/hitel-scribd-runner")
WORKFLOW="seoul-ota-public-contacts.yml"
ARTIFACT="seoul-public-ota-contact-audit"
def command(*cmd,timeout=45,check=True):
    p=subprocess.run(cmd,text=True,capture_output=True,timeout=timeout)
    if check and p.returncode:raise RuntimeError(f"CMD {cmd[:3]}: {p.stdout[-250:]} {p.stderr[-400:]}")
    return p
def state_count(path):
    if not path.exists():return 0
    try:return int(json.loads(path.read_text(encoding="utf-8"))["total_stages_completed"])
    except Exception:return 0
def api(path):
    p=command("gh","api",path,timeout=40)
    return json.loads(p.stdout)
def recover():
    current=state_count(ROOT/"state.json")
    print("RECOVERY_CURRENT_STAGE_TOTAL",current,flush=True)
    try:
        try:
            runs=api(f"repos/{REPO}/actions/workflows/{WORKFLOW}/runs?per_page=35")["workflow_runs"]
        except Exception:
            runs=api(f"repos/{REPO}/actions/runs?per_page=100")["workflow_runs"]
    except Exception as e:
        print("RECOVERY_RUN_LIST_FAILED",repr(e),flush=True)
        return False
    eligible=[x for x in runs if x.get("path","").endswith("/"+WORKFLOW)
      and x.get("status")=="completed"
      and x.get("conclusion") in {"success","failure","cancelled","timed_out"}]
    best_stage=current
    best_id=None
    best_dir=None
    with tempfile.TemporaryDirectory(prefix="seoul-ota-restore-") as tmp:
        folder=Path(tmp)
        for r in eligible[:12]:
            run_id=r["id"]
            try:
                artifacts=api(f"repos/{REPO}/actions/runs/{run_id}/artifacts?per_page=100").get("artifacts",[])
                if not any(x.get("name")==ARTIFACT and not x.get("expired",False) for x in artifacts):
                    continue
                target=folder/str(run_id)
                target.mkdir()
                p=command("gh","run","download",str(run_id),"--repo",REPO,
                           "--name",ARTIFACT,"--dir",str(target),timeout=120,check=False)
                if p.returncode:
                    print("RECOVERY_ARTIFACT_UNAVAILABLE",run_id,p.stderr[-180:],flush=True)
                    continue
                data=target/"data/seoul-ota"
                n=state_count(data/"state.json")
                if n>best_stage and (data/"permit_history.json").exists() and (data/"search_attempts.csv").exists():
                    best_stage=n
                    best_id=run_id
                    best_dir=data
                    print("RECOVERY_CANDIDATE",run_id,n,flush=True)
            except Exception as e:
                print("RECOVERY_CANDIDATE_ERROR",run_id,repr(e),flush=True)
        if best_dir is None:
            print("RECOVERY_UP_TO_DATE",current,flush=True)
            return False
        # These are all generated by the same single-writer workflow. Keep manually
        # curated contact seeds, scripts and files introduced after the artifact.
        ROOT.mkdir(parents=True,exist_ok=True)
        allowed={"state.json","permit_history.json","search_attempts.csv",
                 "listing_evidence.csv","all_properties_contact_summary.csv",
                 "all_public_contact_evidence.csv","all_listing_links.csv","manifest.json"}
        for filename in allowed:
            p=best_dir/filename
            if p.exists():
                (ROOT/filename).write_bytes(p.read_bytes())
        record={
            "recovered_at":dt.datetime.now(dt.timezone.utc).isoformat(),
            "from_run":best_id,"before":current,"after":best_stage,
            "reason":"Artifact stage count exceeded last committed branch state",
            "source":"GitHub Actions public OTA audit artifact",
        }
        (ROOT/"last_recovery.json").write_text(
            json.dumps(record,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    # Commit the recovery before starting new searches.
    command("python3","tools/realestate/seoul_ota_checkpoint.py",
            "--phase","recovered",timeout=150)
    print("RECOVERY_COMMITTED",best_id,best_stage,flush=True)
    return True
if __name__=="__main__":recover()
